"""Writes src/brand/titleGlyphs.js: the outlines of the discipline titles' letters, from the site's own Outfit.

Run it again after renaming a discipline to a title with new letters. It needs fonttools and brotli:
  python3 -m venv /tmp/fonts && /tmp/fonts/bin/pip install fonttools brotli
  /tmp/fonts/bin/python scripts/title-outlines.py
"""
import json
import re
from pathlib import Path

from fontTools.pens.basePen import decomposeQuadraticSegment
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
WEIGHT = 600  # .page-title
MAX_ANCHORS = 4  # per contour, so the pen doesn't litter the title with handles

source = (ROOT / "src/data/disciplines.js").read_text()
titles = re.findall(r'title: "([^"]+)"', source)
font = instancer.instantiateVariableFont(TTFont(ROOT / "public/assets/brand/fonts/outfit-latin.woff2"), {"wght": WEIGHT})
glyph_set = font.getGlyphSet()
cmap = font.getBestCmap()
scale = 1000 / font["head"].unitsPerEm


def n(value):
    return round(value * scale)


def point(p):
    return f"{n(p[0])} {n(-p[1])}"


def contours(name):
    pen = DecomposingRecordingPen(glyph_set)
    glyph_set[name].draw(pen)
    found, d, nodes = [], [], []
    current = None
    for op, args in pen.value:
        if op == "moveTo":
            d, nodes = [f"M{point(args[0])}"], [args[0]]
            current = args[0]
        elif op == "lineTo":
            d.append(f"L{point(args[0])}")
            nodes.append(args[0])
            current = args[0]
        elif op == "qCurveTo":
            for control, end in decomposeQuadraticSegment(args):
                d.append(f"Q{point(control)} {point(end)}")
                current = end
            nodes.append(current)
        elif op == "curveTo":
            d.append(f"C{point(args[0])} {point(args[1])} {point(args[2])}")
            nodes.append(args[2])
            current = args[2]
        elif op in ("closePath", "endPath"):
            step = max(1, len(nodes) // MAX_ANCHORS)
            found.append({"d": "".join(d) + "Z", "anchors": [[n(p[0]), n(-p[1])] for p in nodes[::step][:MAX_ANCHORS]]})
    return found


glyphs = {char: contours(cmap[ord(char)]) for char in sorted(set("".join(titles))) if char != " "}
body = json.dumps(glyphs, separators=(",", ":"), ensure_ascii=False)
(ROOT / "src/brand/titleGlyphs.js").write_text(
    "// Generated by scripts/title-outlines.py from Outfit at weight 600: each letter's contours in thousandths of an em,\n"
    "// from its origin on the baseline, with a few anchor points for the pen.\n"
    f"export const TITLE_GLYPHS = {body}\n"
)
print(titles, len(glyphs), "letters")
